// index.html의 getDayOfYear/renderDictionaryToday 로직 이식 — 매일 결정론적으로 같은 용어를 보여준다.
function getDayOfYear(d: Date): number {
  const start = new Date(d.getFullYear(), 0, 0);
  return Math.floor((d.getTime() - start.getTime()) / 86400000);
}

export function getTodayTerm(): DictionaryTerm {
  const idx = getDayOfYear(new Date()) % DICTIONARY_TERMS.length;
  return DICTIONARY_TERMS[idx];
}
